#!/usr/bin/env node
/**
 * Writes output/pending-migrations.sql: every Rift migration, in order, as one
 * file that is safe to paste into the Supabase SQL editor whatever state the
 * production database is in.
 *
 *   npm run rift:pending-migrations
 *
 * Why every migration rather than "the ones not yet applied": nobody can say
 * with certainty which those are. Production has been caught up by hand in the
 * SQL editor, there is no migrations table to ask, and a file that assumes a
 * starting point fails halfway through on the first table it did not expect.
 *
 * Most migrations are written to re-run (`if not exists`, drop-then-add). The
 * ones from 23 September onwards that create tables inside begin/commit are
 * not, and rewriting shipped migrations to make them so would mean the file in
 * the repository and the one that was applied no longer match. Instead each of
 * those runs only when an object it creates is missing, inside a DO block,
 * which is also a single transaction, so it applies completely or not at all.
 *
 * lib/db/pending-migrations.test.ts applies the output twice to an empty
 * database and once to a database already at each stage, and fails if a new
 * migration neither re-runs cleanly nor has an entry below. That is the
 * signal to add one.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const DIR = "supabase/migrations";
export const OUTPUT = "output/pending-migrations.sql";

/**
 * Migrations that cannot run twice, and the object whose existence means it
 * already has. The first table each one creates: a migration runs in one
 * transaction, so if that exists the rest does too.
 */
export const APPLIED_WHEN = {
  "20260923010000_rift_journeys": "public.rift_journeys",
  "20260923020000_rift_journey_members": "public.rift_journey_members",
  "20260923030000_rift_search": "public.rift_search_revisions",
  "20260923040000_rift_shortlist": "public.rift_shortlist_homes",
  "20260924000000_rift_tours": "public.rift_tour_stops",
  "20260924010000_rift_progress": "public.rift_transactions",
  "20260924020000_rift_offers_documents": "public.rift_documents",
  "20260924030000_rift_deadlines_jobs": "public.rift_deadlines",
  "20260925010000_rift_reconciliations": "public.rift_reconciliations",
  "20260928000000_rift_step_marks": "public.rift_step_marks",
};

export function riftMigrations() {
  return readdirSync(DIR)
    .filter((f) => f.endsWith(".sql") && f.includes("_rift_"))
    .sort()
    .map((f) => ({ name: f.replace(/\.sql$/, ""), sql: readFileSync(`${DIR}/${f}`, "utf8") }));
}

/** A migration that must not run twice, run only when its object is missing. */
function guarded(name, sql, sentinel) {
  /* Its own begin/commit cannot run inside a DO block, and are not needed:
     the block is already one transaction. */
  const body = sql.replace(/^\s*(begin|commit)\s*;\s*$/gim, "");
  const tag = `$m_${name.slice(0, 14)}$`;
  if (body.includes(tag)) throw new Error(`${name} already contains ${tag}`);
  return [
    `do $guard$`,
    `begin`,
    `  if to_regclass('${sentinel}') is not null then`,
    `    raise notice '${name}: already applied, skipped';`,
    `    return;`,
    `  end if;`,
    `  execute ${tag}`,
    body.trim(),
    `${tag};`,
    `end`,
    `$guard$;`,
  ].join("\n");
}

export function pendingMigrationsSql(migrations = riftMigrations()) {
  const known = new Set(migrations.map((m) => m.name));
  for (const name of Object.keys(APPLIED_WHEN)) {
    if (!known.has(name)) throw new Error(`APPLIED_WHEN names ${name}, which is not a migration`);
  }
  const parts = migrations.map(({ name, sql }) => {
    const sentinel = APPLIED_WHEN[name];
    return [
      `-- =====================================================================`,
      `-- ${name}.sql${sentinel ? `  (skipped when ${sentinel} exists)` : ""}`,
      `-- =====================================================================`,
      sentinel ? guarded(name, sql, sentinel) : sql.trim(),
    ].join("\n");
  });
  return [
    `-- Rift: every migration, in order, safe to run on the production database`,
    `-- whatever it already has. Generated by scripts/pending-migrations.mjs from`,
    `-- ${migrations.length} files, the last ${migrations.at(-1)?.name}.`,
    `--`,
    `-- Supabase dashboard > SQL Editor > New query > paste all of this > Run.`,
    `-- Running it twice is safe: a part the database already has is skipped.`,
    ``,
    ``,
    parts.join("\n\n\n"),
    ``,
    `-- PostgREST reloads its schema cache within a minute. Until it does, the`,
    `-- first write to a new column can fail with a message about a schema cache.`,
    `notify pgrst, 'reload schema';`,
    ``,
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, pendingMigrationsSql());
  console.log(`wrote ${OUTPUT}`);
}
