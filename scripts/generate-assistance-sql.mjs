#!/usr/bin/env node
/**
 * Writes the migration that loads the Georgia assistance engine's records
 * (lib/core/assistance.ts) into rift_programs, and retires every row that is
 * not one of them.
 *
 *   node scripts/generate-assistance-sql.mjs > supabase/migrations/<stamp>_rift_assistance_programs.sql
 *   npm run rift:seed-programs     (the same statements, as the local and test seed)
 *
 * The seed used to be generated from the specification's placeholder
 * registry (lib/core/registry.ts) and ran after the migrations, so every local
 * database and test run put the retired placeholders back as active rows.
 *
 * The TypeScript file is the source of truth (Blueprint v5 §6.2); this keeps
 * the table the older readout and Operations read from in step with it. The
 * full record is stored in `rules`, and the older columns are filled from it.
 */
const { GEORGIA_PROGRAMS, toLegacy } = await import("../lib/core/assistance.ts");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${(a ?? []).map(q).join(",")}]::text[]`;
const rows = GEORGIA_PROGRAMS.map((p) => {
  const l = toLegacy(p);
  return `  (${[
    q(l.id), q(l.name), q(l.administrator), q(l.type), q(l.funding),
    l.min, l.max, q(l.county), l.firstTimeOnly, "null", q(l.source),
    q(l.incomeLimitNote), q(l.priceCapNote), arr(l.conditions),
    q(l.verifiedOn), q(l.verifiedBy), q(p.sourceUrl), p.status === "active",
    `${q(JSON.stringify(p))}::jsonb`,
  ].join(", ")})`;
}).join(",\n");

const slugs = GEORGIA_PROGRAMS.map((p) => q(p.slug)).join(", ");

process.stdout.write(`-- GENERATED by scripts/generate-assistance-sql.mjs from lib/core/assistance.ts.
-- Do not edit by hand; change the records and regenerate.
--
-- Blueprint v5 §6 (decision D17): Georgia assistance comes from Rift's own
-- records, built from each administering organization's official page. This
-- loads them into rift_programs and retires every other row, including the
-- placeholder programmes the table was first seeded with. Retired rows are
-- kept (active = false), not deleted: snapshots already issued name them.
--
-- The type and funding checks widen for two honest states: "assistance"
-- (help through a lender whose terms the lender explains) and "confirm"
-- (funding availability must be confirmed with the program).

alter table rift_programs add column if not exists rules jsonb;
alter table rift_programs drop constraint if exists rift_programs_type_check;
alter table rift_programs add constraint rift_programs_type_check
  check (type in ('grant','forgivable','deferred','second-lien','assistance'));
alter table rift_programs drop constraint if exists rift_programs_funding_state_check;
alter table rift_programs add constraint rift_programs_funding_state_check
  check (funding_state in ('open','waitlist','closed','confirm'));

update rift_programs set active = false where slug not in (${slugs});

insert into rift_programs (
  slug, name, administrator, type, funding_state,
  amount_min, amount_max, county, first_time_only, reopens, source_note,
  income_limit_note, price_cap_note, conditions, verified_on, verified_by, source_url, active, rules
) values
${rows}
on conflict (slug) do update set
  name = excluded.name,
  administrator = excluded.administrator,
  type = excluded.type,
  funding_state = excluded.funding_state,
  amount_min = excluded.amount_min,
  amount_max = excluded.amount_max,
  county = excluded.county,
  first_time_only = excluded.first_time_only,
  reopens = excluded.reopens,
  source_note = excluded.source_note,
  income_limit_note = excluded.income_limit_note,
  price_cap_note = excluded.price_cap_note,
  conditions = excluded.conditions,
  verified_on = excluded.verified_on,
  verified_by = excluded.verified_by,
  source_url = excluded.source_url,
  active = excluded.active,
  rules = excluded.rules;
`);
