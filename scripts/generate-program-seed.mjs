#!/usr/bin/env node
/**
 * Generates supabase/seed/rift_programs.sql from lib/core/registry.ts.
 *
 * Written rather than hand-maintained because the registry is the one dataset
 * where the database and the engine disagreeing produces a wrong number in
 * front of a stranger — a programme the matcher knows about and the database
 * does not, or worse, two different amounts for the same programme.
 *
 * Run after any registry change:  node scripts/generate-program-seed.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("lib/core/registry.ts", "utf8");

/* The registry is a literal array of object literals. Rather than pull in a TS
   loader, evaluate just that array — it contains no expressions. */
const start = src.indexOf("export const PROGRAMS");
/* Anchor on the assignment, not the first "[" — the type annotation
   `AssistanceProgram[]` contains one and silently yielded an empty array. */
const open = src.indexOf("[", src.indexOf("=", start));
let depth = 0, end = open;
for (let i = open; i < src.length; i++) {
  if (src[i] === "[") depth++;
  else if (src[i] === "]") { depth--; if (depth === 0) { end = i; break; } }
}
const literal = src.slice(open, end + 1)
  .replace(/_(?=\d)/g, "")              // 10_000 -> 10000
  .replace(/\/\*[\s\S]*?\*\//g, "")     // block comments
  .replace(/\/\/.*$/gm, "");            // line comments

const programs = eval(literal);
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${(a ?? []).map(q).join(",")}]::text[]`;

const rows = programs.map((p) => `  (${[
  q(p.id), q(p.name), q(p.administrator), q(p.type), q(p.funding),
  p.min, p.max, q(p.county), p.firstTimeOnly, q(p.reopens ?? null), q(p.source ?? ""),
  q(p.incomeLimitNote), q(p.priceCapNote), arr(p.conditions),
  q(p.verifiedOn), q(p.verifiedBy),
].join(", ")})`).join(",\n");

const sql = `-- GENERATED by scripts/generate-program-seed.mjs — do not edit by hand.
-- Source of truth: lib/core/registry.ts
-- Regenerate after any registry change, or the engine and the database will
-- disagree about a number a stranger is shown.
--
-- ${programs.length} programmes. Amounts are estimated RANGES with conditions
-- attached, never approvals.

insert into rift_programs (
  slug, name, administrator, type, funding_state,
  amount_min, amount_max, county, first_time_only, reopens, source_note,
  income_limit_note, price_cap_note, conditions, verified_on, verified_by
) values
${rows}
on conflict (slug) do update set
  name = excluded.name,
  administrator = excluded.administrator,
  type = excluded.type,
  funding_state = excluded.funding_state,
  amount_min = excluded.amount_min,
  amount_max = excluded.amount_max,
  county = excluded.county,
  first_time_only = excluded.first_time_only,
  reopens = excluded.reopens,
  source_note = excluded.source_note,
  income_limit_note = excluded.income_limit_note,
  price_cap_note = excluded.price_cap_note,
  conditions = excluded.conditions,
  verified_on = excluded.verified_on,
  verified_by = excluded.verified_by;
`;

writeFileSync("supabase/seed/rift_programs.sql", sql);
console.log(`wrote supabase/seed/rift_programs.sql — ${programs.length} programmes`);
